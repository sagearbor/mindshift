_COARSE = {"neutral", "angry", "sad", "happy"}
_LEVELS = {"mild", "strong"}


# ---------------------------------------------------------------------------
# Shared helpers
# ---------------------------------------------------------------------------

def _meta_path(wav_path: Path) -> Path:
    return wav_path.with_name(wav_path.stem + "_meta.json")


def _wav_seconds(wav_path: Path) -> tuple[float, int]:
    with wave.open(str(wav_path), "rb") as wf:
        return wf.getnframes() / wf.getframerate(), wf.getframerate()


def _build_turns(meta: dict) -> list[dict]:
    """Same reconstruction as the ladder file: turns are concatenated
    back-to-back with a fixed ``silence_gap_sec`` between them, so
    (start, end) follows exactly from the per-turn ``duration_sec``."""
    gap = meta["silence_gap_sec"]
    turns, t = [], 0.0
    for m in meta["turns"]:
        turns.append({
            "speaker": m["speaker"],
            "text": m["text"],
            "start_time": round(t, 4),
            "end_time": round(t + m["duration_sec"], 4),
        })
        t += m["duration_sec"] + gap
    return turns


def _best_permutation_accuracy(
    truth: list[str], pred: list[str],
) -> tuple[float, int, dict[str, str]]:
    """Exact per-turn accuracy under the best bijection pred-label ->
    truth-label (copied from test_diarize_regression_ladder.py; see its
    docstring for why this beats pairwise Rand agreement here)."""
    truth_labels = sorted(set(truth))
    pred_labels = sorted(set(pred))
    best_acc, best_correct, best_map = -1.0, 0, {}
    width = min(len(truth_labels), len(pred_labels))
    for perm in itertools.permutations(truth_labels, width):
        mapping = dict(zip(pred_labels, perm))
        correct = sum(1 for t, p in zip(truth, pred) if mapping.get(p) == t)
        acc = correct / len(truth)
        if acc > best_acc:
            best_acc, best_correct, best_map = acc, correct, mapping
    return best_acc, best_correct, best_map


def _load_16k_pcm(wav_path: Path) -> tuple[np.ndarray, int]:
    """Production decode path (ffmpeg-backed, guaranteed 16 kHz). The scene
    fixtures are already 16 kHz so this is the stdlib fast path — but going
    through it keeps the contract identical to a real upload."""
    pcm, sr = audio_ingest.decode_to_pcm_16k(wav_path.read_bytes(), wav_path.name)
    assert sr == speaker_id.TARGET_SR
    return pcm, sr


