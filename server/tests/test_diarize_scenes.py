def _all_metas() -> list[Path]:
    return sorted(_AUDIO_DIR.glob("*_meta.json"))


@pytest.mark.parametrize("meta_path", _all_metas(), ids=lambda p: p.stem)
def test_fixture_meta_schema_consistent(meta_path: Path):
    """Every fixture meta must (a) describe turns, (b) agree with its WAV's
    sample rate and length, and (c) — where the richer scene fields are
    present — be internally consistent: speakers/self, expected_nudges,
    emotion_coarse. Legacy metas (physics, family_real, poker6) only get
    the checks their fields support; nothing is assumed."""
    meta = json.loads(meta_path.read_text())
    wav_path = meta_path.with_name(meta_path.name.replace("_meta.json", ".wav"))
    assert wav_path.exists(), f"{meta_path.name} has no WAV alongside it"
    file_sec, file_sr = _wav_seconds(wav_path)

    turns = meta.get("turns") or meta.get("approx_turns")
    assert turns, f"{meta_path.name}: no turns/approx_turns"
    assert all(isinstance(t.get("speaker"), str) and t["speaker"] for t in turns)

    if "sample_rate" in meta:
        assert meta["sample_rate"] == file_sr, (
            f"{meta_path.name}: meta sample_rate {meta['sample_rate']} != "
            f"WAV {file_sr}"
        )

    # Concatenated-TTS fixtures: durations + gaps must reproduce the file.
    if "silence_gap_sec" in meta and all("duration_sec" in t for t in turns):
        expected = (sum(t["duration_sec"] for t in turns)
                    + meta["silence_gap_sec"] * (len(turns) - 1))
        assert abs(expected - file_sec) < 0.01, (
            f"{meta_path.name}: sum(duration_sec)+gaps = {expected:.4f}s but "
            f"WAV is {file_sec:.4f}s"
        )

    # Timestamped fixtures: monotonic, inside the file.
    starts_ends = [
        (t.get("start_time", t.get("approx_start")), t.get("end_time", t.get("approx_end")))
        for t in turns
    ]
    if all(s is not None and e is not None for s, e in starts_ends):
        prev_end = 0.0
        for s, e in starts_ends:
            assert 0 <= s < e, f"{meta_path.name}: bad turn span {s}-{e}"
            assert s >= prev_end - 1e-6, f"{meta_path.name}: turns overlap at {s}"
            prev_end = e
        assert prev_end <= file_sec + 0.05, (
            f"{meta_path.name}: last turn ends at {prev_end}s, WAV is {file_sec:.2f}s"
        )

    # Scene-pack fields (present on the Foundation D fixtures).
    speakers = meta.get("speakers")
    if speakers is not None:
        assert set(t["speaker"] for t in turns) <= set(speakers), (
            f"{meta_path.name}: turn speaker not declared in `speakers`"
        )
        selfs = [k for k, v in speakers.items() if v.get("is_self")]
        assert len(selfs) == 1, f"{meta_path.name}: expected exactly one is_self, got {selfs}"
        assert meta.get("self_speaker") == selfs[0]
        assert meta.get("num_speakers_true") == len(speakers)
        assert all(v.get("voice") for v in speakers.values())

    if any("emotion_coarse" in t for t in turns):
        for i, t in enumerate(turns):
            assert t.get("emotion_coarse") in _COARSE, (
                f"{meta_path.name}: turn {i} emotion_coarse={t.get('emotion_coarse')!r}"
            )
            assert t.get("scripted_emotion"), f"{meta_path.name}: turn {i} lacks scripted_emotion"

    nudges = meta.get("expected_nudges")
    if nudges is not None:
        assert speakers is not None, f"{meta_path.name}: expected_nudges without speakers"
        self_label = meta["self_speaker"]
        seen = []
        for n in nudges:
            idx = n["after_turn_index"]
            assert isinstance(idx, int) and 0 <= idx < len(turns), (
                f"{meta_path.name}: nudge index {idx} out of range"
            )
            assert n["level"] in _LEVELS, f"{meta_path.name}: nudge level {n['level']!r}"
            assert isinstance(n.get("reason"), str) and n["reason"].strip()
            assert turns[idx]["speaker"] == self_label, (
                f"{meta_path.name}: nudge after turn {idx} but that turn is "
                f"{turns[idx]['speaker']}, not self ({self_label}) — a nudge on a "
                f"non-self turn is a false positive by construction"
            )
            seen.append(idx)
        assert seen == sorted(seen), f"{meta_path.name}: nudges must be in turn order"
        # The timeline is hand-authored, so keep it honest against the
        # script itself: every ANGRY self turn gets a nudge, nothing else does.
        angry_self = [
            i for i, t in enumerate(turns)
            if t["speaker"] == self_label and t.get("emotion_coarse") == "angry"
        ]
        assert seen == angry_self, (
            f"{meta_path.name}: expected_nudges {seen} != angry self turns {angry_self}"
        )


def test_scene_metas_match_generator_script():
    """The committed scene metas must be byte-for-byte what
    ``scripts/make_test_recording_scenes.py`` says they are (speaker, text,
    emotion, instruction, coarse class, voices, nudges) — i.e. the script IS
    the ground truth and the meta is its faithful record. Also pins the one
    cross-scene invariant the pack is built on: self is the same voice in
    every scene."""
    import make_test_recording_scenes as gen  # scripts/ is on pytest's pythonpath

    for name, wav_path in _SCENES.items():
        if not wav_path.exists():
            pytest.skip(f"{wav_path.name} missing — generate with "
                        "scripts/make_test_recording_scenes.py")
        meta = json.loads(_meta_path(wav_path).read_text())
        scene = gen.SCENES[name]
        assert meta["speakers"] == scene["speakers"], name
        assert meta["silence_gap_sec"] == scene["silence_gap_sec"], name
        assert meta["expected_nudges"] == scene["expected_nudges"], name
        assert len(meta["turns"]) == len(scene["turns"]), name
        for i, (m, s) in enumerate(zip(meta["turns"], scene["turns"])):
            for key in ("speaker", "text", "scripted_emotion", "instruction"):
                assert m[key] == s[key], f"{name} turn {i} {key}"
            assert m["emotion_coarse"] == gen.EMOTION_COARSE[s["scripted_emotion"]], (name, i)
        assert meta["speakers"][meta["self_speaker"]]["voice"] == gen.SELF_VOICE, name


