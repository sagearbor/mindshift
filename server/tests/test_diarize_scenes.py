"""Foundation D — the shared multi-speaker ESCALATION SCENE fixture pack.

Three acted TTS scenes in ``server/tests/fixtures/audio/`` (generated by
``scripts/make_test_recording_scenes.py``), each with a designated "self"
speaker (always ``Speaker A``, always the SAME OpenAI voice), per-turn
scripted emotions + a coarse class, and a hand-authored expected-nudge
timeline. They exist so the watch-nudge, phone post-analysis and realtime
coaching tracks all test against ONE pack with known voices, known
emotions and a known nudge timeline.

Two kinds of test live here:

1. PURE (always run): every ``*_meta.json`` in the fixture dir is schema-
   consistent with its WAV — turn durations + gaps reproduce the file
   length, speakers/self/nudges/emotion_coarse are internally consistent,
   and the scene metas match the generator script's ``SCENES`` byte-for-
   byte (the same "script diffed against meta" ground-truth check the
   ladder report did by hand for the 2-speaker fixtures).

2. LIVE-GATED (torch + speechbrain present): ``diarize_local.diarize_turns``
   on each scene, scored with exact best-permutation per-turn accuracy and
   PINNED AT THE MEASURED VALUE — the ladder file's rule: if a pin regresses,
   investigate rather than lower the bar; if it improves, raise the pin.
   Plus a cross-scene voiceprint test: self enrolled from ONE scene must
   match self — and only self — in the other two.

MEASURED 2026-08-24 (current pipeline, pinned ECAPA revision, 16 kHz):

  couple_escalation  onyx + coral              num_speakers=2  13/13 = 1.000
  family3            onyx + ballad + nova      num_speakers=3  15/15 = 1.000
  meeting4           onyx + marin/ballad/nova  num_speakers=2  11/17 = 0.647
                     SELF isolated on all 6 of its turns; the three
                     colleagues merged into one cluster (k=3 rejected at
                     marginal cosine 0.339 vs STRONG_SEPARATION_COSINE 0.33 —
                     0.32 at the time; recalibrated 2026-08-27).

The meeting4 number is a REAL LIMIT, not a lazy pin. Four different 4-voice
sets were generated and measured before settling on this one:
  alloy/ballad/sage  -> k=3 (ballad+sage merged, 0.378 > 0.32), 15/19
  echo/ballad/nova   -> k=2 (echo pulled self in),              11/19
  cedar/ballad/nova  -> k=3 (cedar+SELF merged, 0.389 > 0.32),  12/17
  marin/ballad/nova  -> k=2 (colleagues merged; SELF isolated),  11/17  <- shipped
No 4-set of OpenAI TTS voices cleared the k=4 split bar; a scratch probe of
all 13 voices put the best possible worst-pair at ~0.30 single-utterance,
and real pooled centroids run 0.03-0.09 higher than that. The shipped set
is the one whose failure mode is LEAST harmful to the pack's purpose (self
attribution stays perfect, so nudge tests still work); the merged
colleagues are the documented ceiling. When the 4-voice pin here starts
failing UPWARD (num_speakers 3 or 4), that is the pipeline getting better —
re-measure and raise it.

Cross-scene self voiceprint (pooled Speaker A from one scene vs pooled
speakers of another): self 0.89-0.94, every non-self 0.09-0.28 — far either
side of ``speaker_id.MATCH_THRESHOLD`` (0.65).

The permutation-accuracy helper is a deliberate copy of the one in
``test_diarize_regression_ladder.py`` (test modules intentionally don't
import each other here).
"""

